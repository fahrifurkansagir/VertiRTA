from pathlib import Path
from typing import Any


UNIT_B = "\\,B"
UNIT_PCT = "\\%"
UNIT_S = "\\,s"
UNIT_V = "\\,V"
UNIT_KWH = "\\,kWh"
UNIT_M = "\\,m"
UNIT_DEG = "$^\\circ$"

PENDING_LABELS: dict[str, str] = {
    "PENDING_COLAB_G4": "Pending (Colab G4)",
    "PENDING_GITHUB_ACTIONS_ARM64": "Pending (ARM64 CI)",
    "PENDING_GITHUB_ACTIONS_X86_PMU": "Pending (x86 PMU CI)",
    "PENDING_LOCAL_PX4_GZ_SITL": "Pending (PX4/Gz SITL)",
    "PENDING_LOCAL_GPU_SMOKE": "Pending (WSL2 GTX 1650S)",
}


def _latex_escape(text: str) -> str:
    return (
        text.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("%", "\\%")
        .replace("&", "\\&")
        .replace("#", "\\#")
    )


def format_metric_value(val: Any, *, suffix: str = "", decimals: int | None = None) -> str:
    """Format numeric metrics or explicit PENDING_* markers into clean LaTeX (never TBD)."""
    if val is None:
        return "--"
    if isinstance(val, bool):
        return "Yes" if val else "No"
    if isinstance(val, str):
        if val.startswith("PENDING_"):
            if val in PENDING_LABELS:
                return PENDING_LABELS[val]
            tag = val.removeprefix("PENDING_").replace("_", " ").title()
            return f"Pending ({_latex_escape(tag)})"
        return _latex_escape(val)
    if isinstance(val, int):
        if abs(val) >= 10_000:
            formatted = f"{val:,}".replace(",", "{,}")
        else:
            formatted = str(val)
        return f"{formatted}{suffix}"
    if isinstance(val, float):
        if decimals is not None:
            return f"{val:.{decimals}f}{suffix}"
        if val.is_integer():
            return f"{val:.1f}{suffix}"
        s = f"{val:.6f}".rstrip("0")
        if s.endswith("."):
            s += "0"
        return f"{s}{suffix}"
    return _latex_escape(str(val))


def _fmt_pct_or_dash(val: Any, decimals: int = 2) -> str:
    if isinstance(val, (int, float)) and not isinstance(val, bool):
        return format_metric_value(val, suffix=UNIT_PCT, decimals=decimals)
    return format_metric_value(val)


def _row(label: str, value: str, note: str = "") -> str:
    if note:
        return f"{label} & {value} & {note} \\\\"
    return f"{label} & {value} \\\\"


def render_tables_from_manifest(manifest_path: Path, out_tex: Path) -> Path:
    """Generate IEEEtran LaTeX tables directly from a frozen JSON metrics manifest."""
    manifest: dict[str, Any] = json.loads(manifest_path.read_text(encoding="utf-8"))
    v1: dict[str, Any] = manifest.get("v1_atlas", {})
    v2a: dict[str, Any] = manifest.get("v2a_copilot", {})
    v2b: dict[str, Any] = manifest.get("v2b_slz", {})

    lines: list[str] = [
        "% Auto-generated by docs/paper/scripts/generate_latex_tables.py -- DO NOT HAND-EDIT.",
        f"% Source manifest: {manifest_path.name}",
        "",
    ]

    # ------------------------------------------------------------------
    # Table I: Pillar 1 Structural Footprint, Determinism & Latency
    # ------------------------------------------------------------------
    t1_rows: list[str] = []
    if "cortex_m7_flash_bytes" in v1:
        t1_rows.append(
            _row(
                "Cortex-M7 Flash (\\texttt{.text+.data})",
                format_metric_value(v1["cortex_m7_flash_bytes"], suffix=UNIT_B),
                "Budget $<262{,}144$\\,B ($256$\\,KiB)",
            )
        )
    if "cortex_m7_ram_bytes" in v1:
        t1_rows.append(
            _row(
                "Cortex-M7 Static Library RAM",
                format_metric_value(v1["cortex_m7_ram_bytes"], suffix=UNIT_B),
                "Caller-owned static arenas ($<128$\\,KiB)",
            )
        )
    if "cortex_m7_max_frame_bytes" in v1:
        t1_rows.append(
            _row(
                "Cortex-M7 Max Static Stack Frame",
                format_metric_value(v1["cortex_m7_max_frame_bytes"], suffix=UNIT_B),
                "Limit $\\le 4{,}096$\\,B ($0$ dynamic)",
            )
        )
    if "cortex_m7_max_dag_bytes" in v1:
        t1_rows.append(
            _row(
                "Cortex-M7 Max Call-Graph Stack DAG",
                format_metric_value(v1["cortex_m7_max_dag_bytes"], suffix=UNIT_B),
                "Limit $\\le 16{,}384$\\,B ($0$ recursion)",
            )
        )
    if "x86_64_max_frame_bytes" in v1 or "x86_64_max_dag_bytes" in v1:
        x86_frame = format_metric_value(v1.get("x86_64_max_frame_bytes"), suffix=UNIT_B)
        x86_dag = format_metric_value(v1.get("x86_64_max_dag_bytes"), suffix=UNIT_B)
        t1_rows.append(
            _row(
                "Host x86\\_64 Stack Frame / DAG",
                f"{x86_frame} / {x86_dag}",
                "All 8 \\texttt{flight\\_core} modules",
            )
        )
    if "arm_m7_heap_symbols" in v1:
        t1_rows.append(
            _row(
                "Forbidden Heap Symbols (\\texttt{nm})",
                format_metric_value(v1["arm_m7_heap_symbols"]),
                "x86\\_64 \\& Cortex-M7 + \\texttt{--wrap=malloc}",
            )
        )
    if "arch_isolation_files" in v1 or "arch_isolation_violations" in v1:
        iso_v = format_metric_value(v1.get("arch_isolation_violations", 0))
        iso_f = format_metric_value(v1.get("arch_isolation_files"))
        t1_rows.append(
            _row(
                "ASTM F3269-21 Core Isolation",
                f"{iso_v} violations",
                f"{iso_f} core files scanned",
            )
        )
    if "tier3_cputime_p99_us" in v1:
        t3_p50 = format_metric_value(v1.get("tier3_cputime_p50_us"), decimals=2)
        t3_p99 = format_metric_value(v1.get("tier3_cputime_p99_us"), decimals=2)
        t3_p999 = format_metric_value(v1.get("tier3_cputime_p999_us"), decimals=2)
        t1_rows.append(
            _row(
                "Tier-3 \\texttt{THREAD\\_CPUTIME} p50 / p99 / p99.9",
                f"{t3_p50} / {t3_p99} / {t3_p999}\\,$\\mu$s",
                "Local WSL2 x86\\_64 ($100\\text{k}$ ticks)",
            )
        )
    if "tier4_p99_us" in v1:
        t4_p50 = format_metric_value(v1.get("tier4_p50_us"), decimals=2)
        t4_p99 = format_metric_value(v1.get("tier4_p99_us"), decimals=2)
        t4_p999 = format_metric_value(v1.get("tier4_p999_us"), decimals=2)
        t4_steal = format_metric_value(v1.get("tier4_steal_pct", 0.0), suffix=UNIT_PCT)
        t1_rows.append(
            _row(
                "Tier-4 \\texttt{MONOTONIC\\_RAW} p50 / p99 / p99.9",
                f"{t4_p50} / {t4_p99} / {t4_p999}\\,$\\mu$s",
                f"Steal {t4_steal} (CLEAN)",
            )
        )
    if "cbvf_violations_in_brt" in v1:
        t1_rows.append(
            _row(
                "In-BRT CBVF Violations",
                format_metric_value(v1["cbvf_violations_in_brt"]),
                "Deterministic HJI-CBVF-QP guard",
            )
        )
    if "arm64_ci_status" in v1:
        t1_rows.append(
            _row(
                "Cloud ARM64 (\\texttt{ubuntu-24.04-arm}) Cross-ISA",
                format_metric_value(v1["arm64_ci_status"]),
                "Azure Cobalt 100 GitHub Actions CI",
            )
        )

    if t1_rows:
        lines.extend(
            [
                "\\begin{table}[t]",
                "\\centering",
                "\\caption{Pillar 1 Bare-Metal Structural Footprint, Isolation, and Execution Determinism (\\texttt{libvertirta\\_flight\\_core} + \\texttt{rta\\_companion}).}",
                "\\label{tab:tier1_determinism}",
                "\\scriptsize",
                "\\begin{tabular}{@{}lll@{}}",
                "\\toprule",
                "\\textbf{Metric} & \\textbf{Measured / Status} & \\textbf{Gate / Scope} \\\\",
                "\\midrule",
                *t1_rows,
                "\\bottomrule",
                "\\end{tabular}",
                "\\end{table}",
                "",
            ]
        )

    # ------------------------------------------------------------------
    # Table II: Pillar 1 Stratified 6-DOF Survival Atlas & A/B Ablation
    # ------------------------------------------------------------------
    t2_rows: list[str] = []
    csfl_n_str = format_metric_value(v1.get("csfl_n"))
    cel_n_str = format_metric_value(v1.get("cel_n"))
    if "csfl_pass_pct" in v1 or "cel_pass_pct" in v1:
        csfl_pass = _fmt_pct_or_dash(v1.get("csfl_pass_pct"))
        csfl_cp = _fmt_pct_or_dash(v1.get("csfl_cp95_upper_pct"))
        cel_pass = _fmt_pct_or_dash(v1.get("cel_pass_pct"))
        cel_cp = _fmt_pct_or_dash(v1.get("cel_cp95_upper_pct"))
        t2_rows.append(
            f"\\textbf{{HJ-CBVF + INDI-WLS}} & {csfl_pass} ($n={csfl_n_str}$) & "
            f"{csfl_cp} & {cel_pass} ($n={cel_n_str}$) & {cel_cp} \\\\"
        )
    elif "csfl_n" in v1 or "cel_n" in v1:
        t2_rows.append(
            f"\\textbf{{HJ-CBVF + INDI-WLS}} & $n={csfl_n_str}$ & -- & $n={cel_n_str}$ & -- \\\\"
        )

    if "hocbf_csfl_pass_pct" in v1:
        h_csfl = _fmt_pct_or_dash(v1.get("hocbf_csfl_pass_pct"))
        h_cp = _fmt_pct_or_dash(v1.get("hocbf_csfl_cp95_upper_pct"))
        h_cel = _fmt_pct_or_dash(v1.get("hocbf_cel_pass_pct", 100.0))
        c_cp = _fmt_pct_or_dash(v1.get("cel_cp95_upper_pct"))
        t2_rows.append(f"HOCBF + INDI-WLS & {h_csfl} & {h_cp} & {h_cel} & {c_cp} \\\\")

    if "stock_ca_cel_pass_pct" in v1:
        s_csfl = _fmt_pct_or_dash(v1.get("stock_ca_csfl_pass_pct", v1.get("csfl_pass_pct")))
        s_cp = _fmt_pct_or_dash(v1.get("csfl_cp95_upper_pct"))
        s_cel = _fmt_pct_or_dash(v1.get("stock_ca_cel_pass_pct"))
        t2_rows.append(f"HJ-CBVF + Stock CA & {s_csfl} & {s_cp} & {s_cel} & 100.00\\% \\\\")

    atlas_footer_parts: list[str] = []
    if "csfl_k" in v1:
        atlas_footer_parts.append(f"CSFL failures $k={format_metric_value(v1['csfl_k'])}$")
    if "cel_k" in v1:
        atlas_footer_parts.append(f"CEL failures $k={format_metric_value(v1['cel_k'])}$")
    if "cliff_failures" in v1:
        cliffs = format_metric_value(v1["cliff_failures"])
        n_tot = format_metric_value(v1.get("total_runs_per_cfg", 10000))
        atlas_footer_parts.append(f"Total cliff ledger entries: {cliffs} / {n_tot}")
    if "ab_total_simulations" in v1:
        ab_tot = format_metric_value(v1["ab_total_simulations"])
        wall_s = format_metric_value(v1.get("wall_clock_total_s"), suffix=UNIT_S, decimals=2)
        atlas_footer_parts.append(f"{ab_tot} total 6-DOF sims in {wall_s}")
    if "zero_failure_1e9_fh" in v1:
        fh_str = format_metric_value(v1["zero_failure_1e9_fh"])
        atlas_footer_parts.append(f"Zero-failure $10^{{-9}}$/FH horizon: {fh_str}\\,FH")
    if "tier2_gazebo_1k_status" in v1:
        t2_st = format_metric_value(v1["tier2_gazebo_1k_status"])
        atlas_footer_parts.append(f"Tier-2 PX4/Gz 1k: {t2_st}")
    if "tier3_lidar_50_status" in v1:
        t3_st = format_metric_value(v1["tier3_lidar_50_status"])
        atlas_footer_parts.append(f"Tier-3 EGL LiDAR 50: {t3_st}")

    if t2_rows:
        lines.extend(
            [
                "\\begin{table*}[t]",
                "\\centering",
                "\\caption{Pillar 1 Tier-1 6-DOF Stratified Survival Envelope Atlas \\& A/B Ablation (Isolated CSFL vs.\\ Same-Arm CEL Denominators; One-Sided 95\\% Clopper-Pearson Upper Failure Bounds).}",
                "\\label{tab:tier1_atlas}",
                "\\scriptsize",
                "\\begin{tabular}{@{}lcccc@{}}",
                "\\toprule",
                "\\textbf{Controller / Filter Config} & \\textbf{CSFL Pass (S2+S3+S5)} & \\textbf{CSFL CP95 Upper} & \\textbf{CEL Pass (S4 Same-Arm)} & \\textbf{CEL CP95 Upper} \\\\",
                "\\midrule",
                *t2_rows,
                "\\bottomrule",
                "\\end{tabular}",
            ]
        )
        if atlas_footer_parts:
            lines.append("")
            lines.append("\\vspace{2pt}")
            lines.append("{\\tiny " + "; ".join(atlas_footer_parts) + ".}")
        lines.extend(["\\end{table*}", ""])

    # ------------------------------------------------------------------
    # Table III: Pillars 2 & 3 Architectural Locks & Evaluation Status
    # ------------------------------------------------------------------
    t3_rows: list[str] = []
    v2a_specs = [
        ("Pillar 2: Conformal Quantile Level $q_{\\text{lvl}}$", "conformal_q_level", "", None),
        ("Pillar 2: Compact GBNF DSL Token Cap", "dsl_max_tokens", " tokens", None),
        ("Pillar 2: Bounded-STL AST Node Cap", "stl_max_nodes", " nodes", None),
        ("Pillar 2: Z3 \\texttt{QF\\_LRA} Timeout Cap", "z3_timeout_ms", "\\,ms", None),
        ("Pillar 2: HV Pack Contract (Voltage / Energy)", None, "", None),
        ("Pillar 2: Unsafe Command Rejection Rate", "unsafe_rejection_pct", UNIT_PCT, 1),
        ("Pillar 2: Conformal Empirical Coverage", "conformal_cov_pct", UNIT_PCT, 1),
        ("Pillar 2: Human-Audited VertiBench-TR/EN", "vertibench_human_audit", "", None),
    ]
    for label, key, suf, dec in v2a_specs:
        if key is None:
            if "pack_nominal_volts" in v2a and "pack_energy_kwh" in v2a:
                v_str = format_metric_value(v2a["pack_nominal_volts"], suffix=UNIT_V, decimals=1)
                e_str = format_metric_value(v2a["pack_energy_kwh"], suffix=UNIT_KWH, decimals=1)
                t3_rows.append(
                    _row(label, f"{v_str} / {e_str}", "Locked to \\texttt{vehicle\\_x8\\_240.yaml}")
                )
            continue
        if key in v2a:
            val = v2a[key]
            is_num = isinstance(val, (int, float)) and not isinstance(val, bool)
            t3_rows.append(
                _row(
                    label,
                    format_metric_value(val, suffix=suf if is_num else "", decimals=dec if is_num else None),
                    "Verified lock" if is_num else "Deferred training/eval",
                )
            )

    v2b_specs = [
        ("Pillar 3: Cell-Local 2.5D SLZ Grid Footprint", "slz_grid_mib", "\\,MiB", 4),
        ("Pillar 3: Pad Footprint Disk ($R_{\\text{SLZ}}\\ge 5$\\,m)", "slz_disk_cells", " cells", None),
        ("Pillar 3: Geometry Gates ($R_{\\min} / \\theta_{\\max} / \\sigma_{z,\\max}$)", None, "", None),
        ("Pillar 3: Perception Staleness Contract", "staleness_limit_ms", "\\,ms", None),
        ("Pillar 3: Active Orbit Safe Touchdown", "active_safe_touchdown_pct", UNIT_PCT, 1),
        ("Pillar 3: Active Orbit False-Commit Rate", "active_false_commit_pct", UNIT_PCT, 1),
        ("Pillar 3: Zero-Shot AeroScapes mIoU", "aeroscape_miou_pct", UNIT_PCT, 1),
        ("Pillar 3: Free-Energy OOD AUROC", "ood_auroc", "", 3),
        ("Pillar 3: Local WSL2 GTX 1650S Peak VRAM", "wsl2_vram_mb", "\\,MB", 1),
        ("Pillar 3: Local WSL2 3/3 Smoke Touchdowns", "wsl2_smoke_status", "", None),
    ]
    for label, key, suf, dec in v2b_specs:
        if key is None:
            if all(k in v2b for k in ("slz_min_radius_m", "slz_max_slope_deg", "slz_max_roughness_m")):
                r_str = format_metric_value(v2b["slz_min_radius_m"], suffix=UNIT_M, decimals=1)
                s_str = format_metric_value(v2b["slz_max_slope_deg"], suffix=UNIT_DEG, decimals=1)
                z_str = format_metric_value(v2b["slz_max_roughness_m"], suffix=UNIT_M, decimals=2)
                t3_rows.append(
                    _row(label, f"{r_str} / {s_str} / {z_str}", "Enforced by \\texttt{SlzBeliefGrid}")
                )
            continue
        if key in v2b:
            val = v2b[key]
            is_num = isinstance(val, (int, float)) and not isinstance(val, bool)
            t3_rows.append(
                _row(
                    label,
                    format_metric_value(val, suffix=suf if is_num else "", decimals=dec if is_num else None),
                    "Verified lock" if is_num else "Deferred GPU campaign",
                )
            )

    if t3_rows:
        lines.extend(
            [
                "\\begin{table}[t]",
                "\\centering",
                "\\caption{Pillars 2 \\& 3 Verified Architectural Locks and Pending Cloud/GPU Evaluation Campaigns (Zero Fabricated Metrics).}",
                "\\label{tab:pillars23_status}",
                "\\scriptsize",
                "\\begin{tabular}{@{}lll@{}}",
                "\\toprule",
                "\\textbf{Subsystem / Metric} & \\textbf{Value / Status} & \\textbf{Evidence Tier} \\\\",
                "\\midrule",
                *t3_rows,
                "\\bottomrule",
                "\\end{tabular}",
                "\\end{table}",
                "",
            ]
        )

    out_tex.parent.mkdir(parents=True, exist_ok=True)
    out_tex.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")
    return out_tex


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate VertiRTA IEEEtran LaTeX tables from JSON manifest.")
    parser.add_argument("--manifest", type=Path, default=Path("docs/paper/metrics_manifest.json"))
    parser.add_argument("--out", type=Path, default=Path("docs/paper/generated/tables.tex"))
    args = parser.parse_args()
    out = render_tables_from_manifest(args.manifest, args.out)
    print(f"Generated {out} ({out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
